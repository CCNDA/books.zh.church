<?php
declare(strict_types=1);
// 出版日期解析單元測試（Asana 1220948673053089）。用法：php tests/test_pubdate.php [lib 路徑]
require $argv[1] ?? dirname(__DIR__) . '/tools/lib_pubdate.php';

$ny = (int) date('Y') + 1;
$cases = [
    // 照舊的西元格式
    ['20040819', ['2004-08', '2004-08-19']],
    ['2004-08-19', ['2004-08', '2004-08-19']],
    ['200408', ['2004-08', '2004-08']],
    ['2004', ['2004', '2004']],
    ['2004年8月', ['2004-08', '2004-08']],
    // 民國 2 碼年（正式庫實例 9305-01-01、6707-01-01）
    ['9305-01-01', ['2004-05', '2004-05-01']],
    ['930501', ['2004-05', '2004-05-01']],
    ['6707-01-01', ['1978-07', '1978-07-01']],
    // 民國 3 碼年（0111-04-26 正式庫實例、1100801）
    ['0111-04-26', ['2022-04', '2022-04-26']],
    ['1100801', ['2021-08', '2021-08-01']],
    ['110/08/01', ['2021-08', '2021-08-01']],
    // 假日期 → 空
    ['1899-12-30', [null, null]],
    ['1900-01-01', [null, null]],
    ['0000-00-00', [null, null]],
    ['189912', [null, null]],
    // 認不出來 → 空，不要猜
    ['2108-01', [null, null]],
    ['0008-11-01', [null, null]],
    ['0205-03-01', [null, null]],
    ['', [null, null]],
    ['abc', [null, null]],
    // 月份不合法只留年份（舊版會變成月份 71）
    ['2026715', ['2026', '2026']],
    // 明年預購照收、後年不收
    [(string) $ny . '0301', [$ny . '-03', $ny . '-03-01']],
];
$pass = 0; $fail = 0;
foreach ($cases as [$in, $want]) {
    $got = parse_date($in);
    if ($got === $want) { $pass++; } else { $fail++; echo "  FAIL ", json_encode($in), " → ", json_encode($got), " 要 ", json_encode($want), "\n"; }
}
// 另外：後年的西元日期不能被當成民國或照收
$far = (string) ($ny + 1) . '0301';
$g = parse_date($far);
if ($g === [null, null]) { $pass++; } else { $fail++; echo "  FAIL 後年 {$far} → ", json_encode($g), "\n"; }
echo "結果：PASS {$pass}／FAIL {$fail}\n";
exit($fail ? 1 : 0);
