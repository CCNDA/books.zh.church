-- ★★ 必跑的驗證一:對映到「站內不存在的分類名」會靜默不歸類,不會報錯。
--    應回 0 列;有回列就是 internal_name 打錯或站內分類改名了。
-- ════════════════════════════════════════════════════════════════════════
SELECT DISTINCT m.internal_name AS 對不到的分類名
  FROM bappress_category_map m
  LEFT JOIN categories c ON c.name = m.internal_name
 WHERE m.internal_name IS NOT NULL AND c.category_id IS NULL;

-- 驗證二:登錄筆數與處置分布(對照 9/21 實測:共 81 列)
SELECT COUNT(*) AS 總列數,
       SUM(internal_name IS NOT NULL) AS 有對映,
       SUM(internal_name IS NULL AND unpublish = 0) AS 僅存證,
       SUM(unpublish = 1) AS 非書下架,
       SUM(note LIKE '%待確認%') AS 待熊哥確認
  FROM bappress_category_map;
-- 預期(補後備主題後):81 / 70 / 9 / 2 / 5
--   70 有對映(61 + 後備主題 9)
--    9 僅存證(主題不單一的書系 6 + 非主題篩選頁 3)
--    2 非書下架(文具、影音)
--    5 待確認:宗教教育(38)、事工教材(39)、崇拜/聖樂(45)、工具書(55)、小冊子(58)
-- ※ 第一次執行(未補後備主題)時是 81 / 61 / 18 / 2 / 5,看到舊數字表示本檔還沒重跑。

-- 驗證三:每個站內分類各接到幾個站方分類(看有沒有哪一類被灌爆)
SELECT m.internal_name AS 站內分類, COUNT(*) AS 站方分類數,
       GROUP_CONCAT(m.bappress_name ORDER BY m.sort_order SEPARATOR '、') AS 明細
  FROM bappress_category_map m
 WHERE m.internal_name IS NOT NULL
 GROUP BY m.internal_name
 ORDER BY 站方分類數 DESC;
