-- unpublish(沿天恩「任一命中即下架」,osb-only 書適用):
--   1=非書(影音3C/工具尺/門訓隨身碟)或非屬靈教材(前程學習/回頭書教材類)
--     ——正常不在抓取範圍,僅防經「★新書到」混入時自動下架。
-- 彙整/促銷分類(★新書到、全部書籍、格子外面出版品、回頭書-全部)
--   internal_name=NULL 僅存證;內容面可於 Navicat 調 internal_name /
--   sort_order / unpublish 後重跑 apply 工具。
-- sort_order:primary 優先序(小者優先;愈具體的主題類愈前,
--   門訓程序類 400 起、彙整類 900 起、下架類 950 起)。
-- 可重跑:INSERT ... ON DUPLICATE KEY 冪等(不覆蓋 internal_name/
--   unpublish/note——表建立後改對映請直接 UPDATE,沿 8/17 衛理教訓)。
--
-- 執行前檢查(名稱須存在於 categories,否則 apply 工具會中止):
--   SELECT name FROM categories ORDER BY sort_order;
-- 本表使用:聖經研究/聖經/神學/倫理/靈修/見證/歷史/門徒造就/教會復興/
--   青少年家庭/兒童教材/詩本樂譜/福音/心理/社會/文學/綜合其他
-- ============================================================

CREATE TABLE IF NOT EXISTS osb_category_map (
  osb_code      VARCHAR(20)  NOT NULL COMMENT '分類代碼(collection handle;=subjects.code)',
  osb_name      VARCHAR(80)  NOT NULL COMMENT '格子外面分類名稱(選單群組>名稱,僅供人讀)',
  internal_name VARCHAR(50)  NULL     COMMENT '對映到的站內 categories.name;NULL=僅存證不歸類',
  unpublish     TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '1=非書或非屬靈教材,osb-only 書命中任一即下架',
  sort_order    INT          NOT NULL DEFAULT 500 COMMENT 'primary 優先序(小者優先)',
  note          VARCHAR(200) NULL     COMMENT '對映說明/待內容面確認事項',
  PRIMARY KEY (osb_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='格子外面官方分類→站內瀏覽分類對映(可於 Navicat 調整)';

