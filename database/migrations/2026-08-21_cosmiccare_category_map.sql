CREATE TABLE IF NOT EXISTS cosmiccare_category_map (
  cc_code       VARCHAR(20)  NOT NULL COMMENT '分類代碼(「大類/子類」截 20 字;=subjects.code)',
  cc_name       VARCHAR(80)  NOT NULL COMMENT '宇宙光分類名稱(大類 > 子類,僅供人讀)',
  internal_name VARCHAR(50)  NULL     COMMENT '對映到的站內 categories.name;NULL=僅存證不歸類',
  unpublish     TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '1=非書,cosmiccare-only 書命中任一即下架',
  sort_order    INT          NOT NULL DEFAULT 500 COMMENT 'primary 優先序(小者優先)',
  note          VARCHAR(200) NULL     COMMENT '對映說明/待內容面確認事項',
  PRIMARY KEY (cc_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='宇宙光官方分類→站內瀏覽分類對映(可於 Navicat 調整)';

