--   unpublish 下架(任一命中即下架,沿天恩/衛理)。
--   ※ 原訂再用商品頁 product_type 判非書**已作廢** —— 實測一張心意卡的
--     product_type 也是 "Books"(那是 OpenCart 屬性群組名稱,全站共用)。
--
-- ★ 分類樹有「捷徑重複掛載」:82/75/140/77/78/139/106/62 等同時是頂層與 73 的子層,
--   兩份都要登錄且對映一致,否則同一本書會因走訪路徑不同而歸到不同分類。
--
-- 出版社/系列彙整分類(環球聖經公會、環球天道傳基協會、熱門系列、作者系列)
--   internal_name=NULL 僅存證不歸類。
-- sort_order:primary 優先序(小者優先;主題類在前、彙整 900 起、下架 950 起)。
-- 可重跑:INSERT ... ON DUPLICATE KEY 冪等(不覆蓋 internal_name/unpublish/note——
--   表建立後改對映請直接 UPDATE,沿 8/17 衛理教訓)。
--
-- 執行前檢查(名稱須存在於 categories,否則 apply 工具會中止):
--   SELECT name FROM categories ORDER BY sort_order;
-- ============================================================

SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS tiendao_category_map (
  td_code       VARCHAR(20)  NOT NULL COMMENT '分類代碼(平台數字 path,如 73_75_62_92;=subjects.code)',
  td_name       VARCHAR(80)  NOT NULL COMMENT '天道分類名稱(僅供人讀)',
  internal_name VARCHAR(50)  NULL     COMMENT '對映到的站內 categories.name;NULL=僅存證不歸類',
  unpublish     TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '1=非書,tiendao-only 書命中任一即下架',
  sort_order    INT          NOT NULL DEFAULT 500 COMMENT 'primary 優先序(小者優先)',
  note          VARCHAR(200) NULL     COMMENT '對映說明/待內容面確認事項',
  PRIMARY KEY (td_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='天道書樓官方分類→站內瀏覽分類對映(可於 Navicat 調整)';

