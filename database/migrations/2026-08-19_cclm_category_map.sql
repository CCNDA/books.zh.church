-- sort_order:primary 優先序(小者優先;主題類在前、彙整 900 起、下架 950 起)。
-- 可重跑:INSERT ... ON DUPLICATE KEY 冪等(不覆蓋 internal_name/
--   unpublish/note——表建立後改對映請直接 UPDATE,沿 8/17 衛理教訓)。
--
-- 執行前檢查(名稱須存在於 categories,否則 apply 工具會中止):
--   SELECT name FROM categories ORDER BY sort_order;
-- ============================================================

CREATE TABLE IF NOT EXISTS cclm_category_map (
  cclm_code     VARCHAR(20)  NOT NULL COMMENT '分類代碼(中文 slug 或 pc{id},截 20 字;=subjects.code)',
  cclm_name     VARCHAR(80)  NOT NULL COMMENT '橄欖華宣分類名稱(群組>名稱,僅供人讀)',
  internal_name VARCHAR(50)  NULL     COMMENT '對映到的站內 categories.name;NULL=僅存證不歸類',
  unpublish     TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '1=非書,cclm-only 書命中任一即下架',
  sort_order    INT          NOT NULL DEFAULT 500 COMMENT 'primary 優先序(小者優先)',
  note          VARCHAR(200) NULL     COMMENT '對映說明/待內容面確認事項',
  PRIMARY KEY (cclm_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='橄欖華宣官方分類→站內瀏覽分類對映(可於 Navicat 調整)';

