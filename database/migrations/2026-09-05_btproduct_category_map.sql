-- ============================================================
-- 單書分類覆蓋表
--
-- 為什麼需要:站方的「宗教」類只有 16 本,卻混了四種書 ——
--   聖經人物/釋經 7、神學 2、靈修 4、見證 3。整類對到任何一個分類都會錯一半以上。
-- 這個機制之後其他來源也用得到(每站總有幾本歸類特別離譜的書)。
-- 套用順序:對映表算完 primary 之後,本表覆蓋(內容面判斷優先於機械對映)。
-- ============================================================

CREATE TABLE IF NOT EXISTS btproduct_book_override (
  pid           VARCHAR(20)  NOT NULL COMMENT '突破商品 id(=subjects 存證的來源 pid / editions.source_url 尾碼)',
  title         VARCHAR(255) NOT NULL COMMENT '書名(僅供人讀,方便核對)',
  internal_name VARCHAR(50)  NULL     COMMENT '指定的站內 categories.name;NULL=不歸類',
  unpublish     TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '1=不上架',
  note          VARCHAR(200) NULL,
  PRIMARY KEY (pid)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='突破機構單書分類覆蓋(內容面判斷,優先於對映表)';

