-- 建立日:2026-09-05
--
-- 背景:第十六個書目來源「突破機構」(www.btproduct.com/tc/book/,香港,1973 年創立的
--   青少年文化機構,PHP 自建站,HKD,繁體;全站書籍 583 種)。海外第一批第 2 站,
--   版號 v1.12.0。沿 7/31 以琳雙軌分類決議:
--   (1) 站方分類由 import.php 寫入 subjects(scheme='btproduct')永久存證;
--   (2) 站內瀏覽分類經本對映表換算(tools/apply_btproduct_categories.php)。
--
-- ★ 本站對映有兩軸,兩軸都在同一張表裡,用 code 前綴分流:
--     主題分類 cat=  → code 是站方 6 位數字 id(如 418988=宗教)
--     系列分類 ser=  → code 是 'S' + 站方數字 id(如 S433277=心理自助)
--   為什麼系列也要進來:全站 583 本裡有 **11 本只有系列、沒有主題分類**
--   (站方資料本身沒填),不吃系列這一軸的話它們只能靠關鍵字猜測。
--   sort_order 讓主題分類一律排在系列之前 → primary 仍由主題分類決定。
--
-- ★ code 用平台數字 id,不用中文名(必查陷阱:分類代碼不可用中文 slug)。
--
-- 抓取範圍(熊哥 9/5 裁示):只取 /tc/book/;禮品區 /tc/gift/ 整區不抓
--   (兩者目錄分流乾淨,不需要靠品名判非書)。故本表的 unpublish 只用於
--   「有抓進來但不該上架」的類別 —— 目前只有教科書。
--
-- 購書連結:本站**沒有購物車**(buy.php 只是批發聯絡資訊)。熊哥裁示:
--   不產生購書連結,商品頁網址以一般連結放在書籍資訊區
--   → import.php 對 btproduct 寫 links.link_type='official'(不是 'buy')。
--
-- 可重跑:INSERT ... ON DUPLICATE KEY 冪等(不覆蓋 internal_name/unpublish/note ——
--   表建立後改對映請直接 UPDATE,沿 8/17 衛理教訓)。
-- ============================================================

CREATE TABLE IF NOT EXISTS btproduct_category_map (
  bt_code       VARCHAR(20)  NOT NULL COMMENT '分類代碼(=subjects.code);cat 為 6 位數字,ser 為 S+數字',
  bt_name       VARCHAR(80)  NOT NULL COMMENT '突破分類名稱(僅供人讀)',
  internal_name VARCHAR(50)  NULL     COMMENT '對映到的站內 categories.name;NULL=僅存證不歸類',
  unpublish     TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '1=不該上架,btproduct-only 書命中任一即下架',
  sort_order    INT          NOT NULL DEFAULT 500 COMMENT 'primary 優先序(小者優先;主題 10-99、系列 500+)',
  note          VARCHAR(200) NULL     COMMENT '對映說明/待內容面確認事項',
  PRIMARY KEY (bt_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='突破機構官方分類→站內分類對映(cat 主題 21 類 + ser 系列 22 類)';

