CREATE TABLE IF NOT EXISTS twgbr_category_map (
  tw_code       VARCHAR(40)  NOT NULL COMMENT '分類 handle(=subjects.code)',
  tw_name       VARCHAR(80)  NOT NULL COMMENT '站方分類名稱(僅供人讀)',
  internal_name VARCHAR(50)  NULL     COMMENT '對映到的站內 categories.name;NULL=僅存證不歸類',
  unpublish     TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '1=非書/外文,twgbr-only 書命中任一即下架',
  sort_order    INT          NOT NULL DEFAULT 500 COMMENT 'primary 優先序(小者優先)',
  note          VARCHAR(200) NULL     COMMENT '對映說明/待內容面確認事項',
  PRIMARY KEY (tw_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='臺灣福音書房分類對映(2026-08-25,51 列 = 站台分類數)';

