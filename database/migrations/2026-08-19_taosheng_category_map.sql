--   (1) 站方分類(導覽選單;歸屬由爬蟲「清單走訪」蒐集,一書多分類)
--       由 import.php 寫入 subjects(scheme='taosheng') 永久存證——
--       code=collection handle(中文 handle 直接入 code,截 20 字)、
--       label=「選單群組 > 名稱」;
--   (2) 站內瀏覽分類經本對映表換算(tools/apply_taosheng_categories.php)。
--
-- 抓取範圍(8/19 決議):**全站抓入存證**(/collections/all,1,637 件),
--   非書(桌遊/月曆/文創/刮刮卡/影音/福音機)由 unpublish 下架
--   (任一命中即下架,沿天恩規則)。代銷他社書全收(8/19 決議)——
--   同 ISBN 自動跨站合併,多一個購書管道。
-- 出版社彙整分類(香港道聲/格子外面/上誼…)internal_name=NULL 僅存證。
-- sort_order:primary 優先序(小者優先;主題類在前、彙整 900 起、下架 950 起)。
-- 可重跑:INSERT ... ON DUPLICATE KEY 冪等(不覆蓋 internal_name/
--   unpublish/note——表建立後改對映請直接 UPDATE,沿 8/17 衛理教訓)。
--
-- 執行前檢查(名稱須存在於 categories,否則 apply 工具會中止):
--   SELECT name FROM categories ORDER BY sort_order;
-- ============================================================

CREATE TABLE IF NOT EXISTS taosheng_category_map (
  ts_code       VARCHAR(20)  NOT NULL COMMENT '分類代碼(collection handle 截 20 字;=subjects.code)',
  ts_name       VARCHAR(80)  NOT NULL COMMENT '道聲分類名稱(選單群組>名稱,僅供人讀)',
  internal_name VARCHAR(50)  NULL     COMMENT '對映到的站內 categories.name;NULL=僅存證不歸類',
  unpublish     TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '1=非書,taosheng-only 書命中任一即下架',
  sort_order    INT          NOT NULL DEFAULT 500 COMMENT 'primary 優先序(小者優先)',
  note          VARCHAR(200) NULL     COMMENT '對映說明/待內容面確認事項',
  PRIMARY KEY (ts_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='道聲官方分類→站內瀏覽分類對映(可於 Navicat 調整)';

