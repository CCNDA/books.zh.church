-- 促銷/彙整分類(新品上架各月份、2025暢銷書、特價區、畅销作家頂層)不入
--   對映表:apply 工具遇未對映 code 自動略過並列入報表。
-- 無自己網址的子分類(伊班圣经、儿童学习卡、小组等 href 同父分類)爬蟲
--   不會產生獨立 code,不入表。
-- 可重跑:INSERT ... ON DUPLICATE KEY 冪等。
--
-- 執行前檢查(名稱須存在於 categories,否則 apply 工具會中止):
--   SELECT name FROM categories ORDER BY sort_order;
-- 本表使用:聖經研究/聖經/神學/倫理/靈修/見證/歷史/門徒造就/教會復興/
--   青少年家庭/兒童教材/兒童主日學/詩本樂譜/福音/心理/社會/文學/綜合其他
-- ============================================================

CREATE TABLE IF NOT EXISTS methodist_category_map (
  mb_code       VARCHAR(20)  NOT NULL COMMENT '分類代碼(SEO slug 末段或 path id,截 20 字;=subjects.code)',
  mb_name       VARCHAR(80)  NOT NULL COMMENT '衛理分類名稱(頂層>子分類,繁體,僅供人讀)',
  internal_name VARCHAR(50)  NULL     COMMENT '對映到的站內 categories.name;NULL=僅存證不歸類',
  unpublish     TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '1=非書或外文書,methodist-only 書命中任一即下架',
  sort_order    INT          NOT NULL DEFAULT 500 COMMENT 'primary 優先序(小者優先)',
  note          VARCHAR(200) NULL     COMMENT '對映說明/待內容面確認事項',
  PRIMARY KEY (mb_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='衛理書房官方分類→站內瀏覽分類對映(可於 Navicat 調整)';

