-- 建立日:2026-08-09
--
-- 背景:新增書目來源「微讀書城」(wdbook.com,WeDevote 純電子書店,USD)。
--   沿 7/31 以琳雙軌分類決議:(1) 微讀官網分類(階層樹:7 頂層 + 38 子分類;
--   商品麵包屑僅帶一個子分類 id)由 import.php 寫入 subjects(scheme='wdbook')
--   永久存證——code=微讀分類 id、label=「頂層 > 子分類」繁體完整路徑;
--   (2) 站內瀏覽分類經本對映表換算(tools/apply_wdbook_categories.php),
--   兩軌皆在庫、互可查照。
--
-- 鍵為微讀分類 id(wd_id):站方分類「名稱」隨介面語系浮動(常回簡體),
--   id 才穩定;wd_name 僅供人讀。internal_name 對映 categories.name,
--   內容面可於 Navicat 直接改 internal_name / sort_order 後重跑 apply 工具。
-- sort_order:primary 優先序(小者優先;愈具體的主題類愈前,泛用類靠後)。
-- unpublish:全站皆電子書、無非書商品,本表全為 0(欄位保留備未來)。
-- 頂層分類(23xxx/3xxxx 系列)一併入表:麵包屑正常只給子分類,
--   頂層列為後備(站方若直掛頂層仍可歸類)。
-- 促銷分類(近期上架/免費電子書/套裝優惠/獨家好書等 88xxx 系列)不入
--   對映表:爬蟲不記促銷分類,apply 工具遇未對映 id 自動略過。
-- 可重跑:INSERT ... ON DUPLICATE KEY 冪等。
-- ============================================================

CREATE TABLE IF NOT EXISTS wdbook_category_map (
  wd_id         VARCHAR(20)  NOT NULL COMMENT '微讀分類 id(穩定;名稱隨語系浮動故不作鍵)',
  wd_name       VARCHAR(60)  NOT NULL COMMENT '微讀分類名稱(繁體,僅供人讀)',
  internal_name VARCHAR(50)  NOT NULL COMMENT '對映到的站內 categories.name',
  unpublish     TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '1=非書商品下架(微讀全為電子書,現皆 0)',
  sort_order    INT          NOT NULL DEFAULT 500 COMMENT 'primary 優先序(小者優先)',
  note          VARCHAR(200) NULL     COMMENT '對映說明/待內容面確認事項',
  PRIMARY KEY (wd_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='微讀書城官方分類→站內瀏覽分類對映(可於 Navicat 調整)';

