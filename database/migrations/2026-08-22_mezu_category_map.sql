--   跨站合併的書不下架(他站有紙本書)。
--
-- 分類依據(8/22 決議):**只有站方 17 個主題分類參與站內分類**;
--   出版社/總代理分類(約 70 個)與促銷彙整(新品上架/注目優惠…)
--   internal_name=NULL **僅存證不歸類**(沿宇宙光作者系列 Tag 的處理),
--   出版社分類另作「出版社」欄位的交叉佐證。
--
-- 欄位解析(8/22 決議):站方商品描述是 Froala 富文本自由文字,欄位標籤
--   不統一(「出版社:」/「出 版 商」),故**原始描述整段存 extra.desc_raw**、
--   通用標籤採集存 extra.spec_all,只有少數白名單欄位入平面欄。
--   → 上線後可用下列 SQL 統計標籤分布,再決定下一版要對映哪些欄位:
--     SELECT JSON_KEYS(JSON_EXTRACT(extra,'$.mezu.spec_all')) FROM books
--       WHERE JSON_EXTRACT(extra,'$.mezu.spec_all') IS NOT NULL LIMIT 50;
--
-- sort_order:primary 優先序(小者優先;主題類 10-260、出版社/其他 300 起、
--   非書下架 600 起、促銷彙整 900 起)。
-- 可重跑:INSERT ... ON DUPLICATE KEY 冪等(**不覆蓋** internal_name/
--   unpublish/note——表建立後改對映請直接 UPDATE,沿 8/17 衛理教訓)。
--
-- 執行前檢查(名稱須存在於 categories,否則 apply 工具會中止):
--   SELECT name FROM categories ORDER BY sort_order;
-- ============================================================

CREATE TABLE IF NOT EXISTS mezu_category_map (
  mz_code       VARCHAR(20)  NOT NULL COMMENT 'collection handle(=subjects.code,截 20 字)',
