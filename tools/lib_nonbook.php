<?php
declare(strict_types=1);

/**
 * 非書籍商品判斷規則（全專案唯一一份；guard_nonbook.php 用）。
 *
 * 收錄判準一（Asana 1218562704413649）：非書籍的周邊商品不收錄，站上既有的也要下架。
 * 2026-10-11 下架 146 筆（delist_list_20261006）之後，熊哥問「有排進每日更新嗎」→ 本規則。
 *
 * ★ 分兩級，因為單靠書名關鍵字會誤傷真的書（2026-10-11 在正式庫複本校準，上架書 54,696 本）：
 *   - A 級：上架書命中 0 本、下架清單有命中的詞 → 每日新品碰到就先下架，列清單給熊哥確認。
 *   - B 級：真的書名裡也會出現的詞（例：《珍珠項鍊》故事書、聖經「筆記本版」、兒童貼紙書）
 *     → 不下架，只列清單給熊哥看。
 *   校準時 A＋B 對 146 筆的抓到率 143／146；漏的三筆：「中英標籤」→ B 級加「標籤」，
 *   「雙層黑鑽十字架(鋯石)」→ A 級加「鋯石」，「祝福筆筆皆是」（筆）抓不到，靠人工。
 * ★ 試過把「十字架」放 B 級：全站上架書命中 103 本，幾乎都是神學書（「十字架的道路」這類），
 *   會淹沒真正要看的清單，所以拿掉；十字架飾品靠 A 級的「鋯石」或飾品詞抓。
 * ★ 不用的詞：「貼」（上架命中 57）、「聖餐」（36，大多是神學書）—— 太廣。
 * ★ 新增 A 級詞之前，先對全站上架書數一次命中數：命中不是 0 就只能放 B 級。
 */

const NB_A_WORDS = [
    '播放器', '索引貼', '標籤貼', '手鍊', '手鏈', '手環', '胸針', '耳環',
    '杯墊', '抱枕', '薄被', '掛畫', '記事本', '紙偶', '磁鐵',
    '鑰匙圈', '吊飾', '馬克杯', '帆布袋', 'T恤', '原子筆', '鋼筆',
    '月曆', '桌曆', '掛曆', '鋯石',
];

const NB_B_WORDS = [
    '貼紙', '項鍊', '項鏈', '戒指', '膏油', '筆記本', '玩偶', '布偶', '公仔', '聖餐杯',
    '字卡', '明信片', '賀卡', '卡片', '禱文卡', '禮盒', '套組', '教具', '標籤',
];

/**
 * @return array{tier: string, word: string}|null  A 級優先；都沒命中回 null
 */
function classify_nonbook(?string $title): ?array
{
    if ($title === null || $title === '') {
        return null;
    }
    foreach (NB_A_WORDS as $w) {
        if (mb_strpos($title, $w) !== false) {
            return ['tier' => 'A', 'word' => $w];
        }
    }
    foreach (NB_B_WORDS as $w) {
        if (mb_strpos($title, $w) !== false) {
            return ['tier' => 'B', 'word' => $w];
        }
    }
    return null;
}
